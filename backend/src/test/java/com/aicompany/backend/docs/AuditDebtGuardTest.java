package com.aicompany.backend.docs;

import org.junit.jupiter.api.Assumptions;
import org.junit.jupiter.api.Test;
import org.w3c.dom.Document;
import org.w3c.dom.Element;
import org.w3c.dom.Node;
import org.w3c.dom.NodeList;

import javax.xml.parsers.DocumentBuilderFactory;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Properties;
import java.util.concurrent.TimeUnit;
import java.util.regex.Pattern;
import java.util.stream.Stream;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * PHASE 32 -- the audit's debts (docs/audit/TECHNICAL_DEBT.md, TASK-000) that are
 * about the build, the configuration and the repository, each held by a check
 * that fails if the defect returns. The charter does not let a debt be closed
 * because the code looks different now; these are the checks that let the
 * registry say "closed".
 *
 * <p>The API-shape debts of the same audit (TD-03, TD-05, TD-06, TD-10) are
 * held by {@code ApiShapeGuardTest}, which needs the classes rather than files.
 */
class AuditDebtGuardTest {

    /** A real import, at the start of a line: a Blueprint fixture that mentions Lombok in a string does not count. */
    private static final Pattern LOMBOK_IMPORT = Pattern.compile("(?m)^import lombok\\.");

    // --- TD-01: volatile persistence (H2 in memory) ----------------------------

    @Test
    void td01_theDataLivesInPostgresNeverInAnInMemoryDatabase() throws Exception {
        assertThat(read("backend/pom.xml")).doesNotContainIgnoringCase("h2database").doesNotContainIgnoringCase("hsqldb");
        for (Path properties : applicationProperties()) {
            assertThat(Files.readString(properties)).as(properties.toString())
                    .doesNotContainIgnoringCase("jdbc:h2").doesNotContainIgnoringCase("jdbc:hsqldb");
        }
        assertThat(property("application-dev.properties", "spring.datasource.url")).startsWith("jdbc:postgresql:");
        assertThat(property("application-prod.properties", "spring.datasource.url")).isEqualTo("${POSTGRES_URL}");
    }

    // --- TD-02: the schema generated by Hibernate, without migrations -----------

    @Test
    void td02_flywayOwnsTheSchemaAndHibernateOnlyValidatesIt() throws Exception {
        assertThat(property("application.properties", "spring.jpa.hibernate.ddl-auto")).isEqualTo("validate");
        assertThat(property("application.properties", "spring.flyway.enabled")).isEqualTo("true");
        for (Path file : applicationProperties()) {
            String value = load(file).getProperty("spring.jpa.hibernate.ddl-auto");
            assertThat(value).as("no profile may let Hibernate change the schema: " + file).isIn(null, "validate", "none");
        }
    }

    // --- TD-16: open-in-view left at its default --------------------------------

    @Test
    void td16_noLazyLoadingDuringSerialization() throws Exception {
        assertThat(property("application.properties", "spring.jpa.open-in-view")).isEqualTo("false");
        for (Path file : applicationProperties()) {
            assertThat(load(file).getProperty("spring.jpa.open-in-view")).as(file.toString()).isIn(null, "false");
        }
    }

    // --- TD-22: no port, no environment configuration ---------------------------

    @Test
    void td22_thePortAndTheSecretsComeFromTheEnvironment() throws Exception {
        assertThat(property("application.properties", "server.port")).matches("\\$\\{SERVER_PORT:\\d+}");
        assertThat(property("application-dev.properties", "spring.datasource.password")).startsWith("${POSTGRES_PASSWORD:");
        assertThat(property("application-prod.properties", "spring.datasource.password")).isEqualTo("${POSTGRES_PASSWORD}");
    }

    // --- TD-21: System.out instead of logging ------------------------------------

    @Test
    void td21_theApplicationLogsItDoesNotPrint() throws Exception {
        List<String> printing = new ArrayList<>();
        try (Stream<Path> sources = Files.walk(root().resolve("backend/src/main/java"))) {
            for (Path source : sources.filter(p -> p.toString().endsWith(".java")).toList()) {
                String code = Files.readString(source, StandardCharsets.UTF_8);
                if (code.contains("System.out.") || code.contains("System.err.") || code.contains(".printStackTrace()")) {
                    printing.add(root().relativize(source).toString());
                }
            }
        }
        assertThat(printing).as("use a Logger").isEmpty();
    }

    // --- TD-15: Lombok declared and never used; TD-19: empty pom metadata --------

    @Test
    void td15_noAnnotationProcessorIsDeclaredThatNothingUses() throws Exception {
        boolean declared = read("backend/pom.xml").contains("<artifactId>lombok</artifactId>");
        boolean used;
        try (Stream<Path> sources = Files.walk(root().resolve("backend/src"))) {
            used = sources.filter(p -> p.toString().endsWith(".java")).anyMatch(p -> {
                try {
                    return LOMBOK_IMPORT.matcher(Files.readString(p, StandardCharsets.UTF_8)).find();
                } catch (IOException e) {
                    throw new IllegalStateException(e);
                }
            });
        }
        assertThat(declared).as("Lombok is declared in the pom but no source imports it").isEqualTo(used);
    }

    @Test
    void td19_theBuildDescribesTheProjectWithoutEmptyPlaceholders() throws Exception {
        Document pom = DocumentBuilderFactory.newInstance().newDocumentBuilder()
                .parse(root().resolve("backend/pom.xml").toFile());
        Element project = pom.getDocumentElement();
        assertThat(child(project, "name")).isNotBlank();
        assertThat(child(project, "description")).isNotBlank();
        assertThat(child(project, "url")).startsWith("https://");

        List<String> empty = new ArrayList<>();
        for (String section : List.of("name", "description", "url", "licenses", "developers", "scm")) {
            NodeList nodes = project.getElementsByTagName(section);
            for (int i = 0; i < nodes.getLength(); i++) {
                collectEmpty((Element) nodes.item(i), empty);
            }
        }
        assertThat(empty).as("metadata elements left empty by the project generator").isEmpty();
    }

    // --- TD-20: Git hygiene --------------------------------------------------------

    @Test
    void td20_nothingTheRepositoryIgnoresIsTracked() throws Exception {
        Assumptions.assumeTrue(Files.exists(root().resolve(".git")), "not a Git checkout");
        Process git = new ProcessBuilder("git", "ls-files", "--cached", "--ignored", "--exclude-standard")
                .directory(root().toFile()).redirectErrorStream(true).start();
        String tracked = new String(git.getInputStream().readAllBytes(), StandardCharsets.UTF_8).strip();
        assertThat(git.waitFor(30, TimeUnit.SECONDS)).isTrue();
        Assumptions.assumeTrue(git.exitValue() == 0, "git is not available: " + tracked);
        assertThat(tracked).as("tracked files that a .gitignore excludes").isEmpty();
        assertThat(read(".gitignore")).contains(".env").contains("target/");
    }

    // --- helpers ------------------------------------------------------------------

    private static void collectEmpty(Element element, List<String> empty) {
        boolean hasChildElements = false;
        for (Node node = element.getFirstChild(); node != null; node = node.getNextSibling()) {
            if (node instanceof Element child) {
                hasChildElements = true;
                collectEmpty(child, empty);
            }
        }
        if (!hasChildElements && element.getTextContent().isBlank()) {
            empty.add("<" + element.getTagName() + "/>");
        }
    }

    private static String child(Element parent, String name) {
        for (Node node = parent.getFirstChild(); node != null; node = node.getNextSibling()) {
            if (node instanceof Element child && child.getTagName().equals(name)) {
                return child.getTextContent().strip();
            }
        }
        return "";
    }

    private static List<Path> applicationProperties() throws IOException {
        try (Stream<Path> files = Files.list(root().resolve("backend/src/main/resources"))) {
            List<Path> found = files.filter(p -> p.getFileName().toString().matches("application.*\\.properties")).toList();
            assertThat(found).as("the configuration files must be found, or these checks prove nothing").isNotEmpty();
            return found;
        }
    }

    private static String property(String file, String key) throws IOException {
        return load(root().resolve("backend/src/main/resources").resolve(file)).getProperty(key);
    }

    private static Properties load(Path file) throws IOException {
        Properties properties = new Properties();
        try (var reader = Files.newBufferedReader(file, StandardCharsets.UTF_8)) {
            properties.load(reader);
        }
        return properties;
    }

    private static String read(String relativePath) throws IOException {
        Path file = root().resolve(relativePath);
        assertThat(Files.exists(file)).as("expected to find " + file).isTrue();
        return Files.readString(file, StandardCharsets.UTF_8);
    }

    /** The repository root: the ancestor with {@code .company-os} (as in DebtRegistryConsistencyTest). */
    private static Path root() {
        Path candidate = Path.of("").toAbsolutePath();
        while (candidate != null) {
            if (Files.isDirectory(candidate.resolve(".company-os"))) {
                return candidate;
            }
            candidate = candidate.getParent();
        }
        throw new IllegalStateException("repository root not found from " + Path.of("").toAbsolutePath());
    }
}
