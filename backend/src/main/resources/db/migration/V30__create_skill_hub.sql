-- PHASE 31 (ADR-036). The Knowledge Hub sees every skill on this machine, finds
-- new ones in online marketplaces, installs them, keeps copies in sync and
-- checks for updates. Additive only: three new tables, nothing existing changes.

-- Where a library entry came from, when the Hub installed or imported it:
-- a marketplace package (skills.sh, ClawHub, a GitHub repository) or a skill
-- found in another application on this machine (provider 'app').
--   reference              owner/repo/path, owner/slug, or location:relative-path
--   installed_fingerprint  the package as it was upstream when installed
--   local_fingerprint      the library folder as the Hub wrote it -- a different
--                          value now means the operator edited it since
--   latest_*               what the last update check found upstream
CREATE TABLE skill_installations (
    id                    BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_id           BIGINT       NOT NULL REFERENCES harness_resources (id) ON DELETE CASCADE,
    provider              VARCHAR(32)  NOT NULL,
    reference             VARCHAR(500) NOT NULL,
    source_url            VARCHAR(500),
    installed_version     VARCHAR(120),
    installed_fingerprint VARCHAR(64)  NOT NULL,
    local_fingerprint     VARCHAR(64)  NOT NULL,
    installed_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    checked_at            TIMESTAMP WITH TIME ZONE,
    latest_version        VARCHAR(120),
    latest_fingerprint    VARCHAR(64),
    check_error           VARCHAR(500),
    version               BIGINT       NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX skill_installations_resource_idx ON skill_installations (resource_id);

-- What the last synchronisation found in the applications' skill folders, so
-- that the next one can say what was installed, removed or changed meanwhile.
CREATE TABLE skill_snapshot (
    id              VARCHAR(40)   PRIMARY KEY,
    app             VARCHAR(32)   NOT NULL,
    location        VARCHAR(48)   NOT NULL,
    relative_path   VARCHAR(1000) NOT NULL,
    name            VARCHAR(200)  NOT NULL,
    fingerprint     VARCHAR(64)   NOT NULL,
    plugin_version  VARCHAR(120),
    first_seen_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    last_changed_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- The Hub's activity log: one row per skill that appeared, disappeared or changed.
CREATE TABLE skill_sync_events (
    id            BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    change        VARCHAR(16)   NOT NULL,
    app           VARCHAR(32)   NOT NULL,
    location      VARCHAR(48)   NOT NULL,
    name          VARCHAR(200)  NOT NULL,
    relative_path VARCHAR(1000) NOT NULL,
    detail        VARCHAR(500),

    CONSTRAINT skill_sync_events_change_check CHECK (change IN ('ADDED', 'REMOVED', 'MODIFIED'))
);
CREATE INDEX skill_sync_events_time_idx ON skill_sync_events (occurred_at DESC);
