-- PHASE 28 (ADR-033). The Project Blueprint: a project's technical components and
-- the relations between them, detected from the code or added by the operator,
-- and editable without ever writing a source file. Additive: five new tables,
-- nothing existing is read, written or altered.
--
-- FKs towards projects carry no ON DELETE, like every other FK of the stream:
-- deleting a project for real (ADR-027) removes its blueprint explicitly. FKs
-- inside the blueprint cascade, by declared choice (ADR-033 §2): an edge is a
-- property of its two ends, a method node a part of its class.

CREATE TABLE blueprint_nodes (
    id              BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id      BIGINT        NOT NULL REFERENCES projects (id),
    node_key        VARCHAR(512)  NOT NULL,
    kind            VARCHAR(32)   NOT NULL,
    origin          VARCHAR(16)   NOT NULL,
    status          VARCHAR(16)   NOT NULL,
    path_state      VARCHAR(24)   NOT NULL,
    name            VARCHAR(255)  NOT NULL,
    file_path       VARCHAR(1000),
    language        VARCHAR(32),
    description     VARCHAR(4000),
    pseudocode      VARCHAR(8000),
    notes           VARCHAR(4000),
    tags            VARCHAR(1000),
    structure       TEXT,
    detected        TEXT,
    overrides       VARCHAR(255),
    start_line      INTEGER,
    end_line        INTEGER,
    parent_id       BIGINT        REFERENCES blueprint_nodes (id) ON DELETE CASCADE,
    expanded        BOOLEAN       NOT NULL DEFAULT FALSE,
    last_scan_id    BIGINT,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    version         BIGINT        NOT NULL DEFAULT 0,

    CONSTRAINT blueprint_nodes_kind_check CHECK (kind IN ('FILE', 'CLASS', 'INTERFACE', 'ENUM', 'FUNCTION',
        'CONTROLLER', 'SERVICE', 'REPOSITORY', 'DTO', 'ENTITY', 'CONFIGURATION', 'DATABASE', 'ENDPOINT',
        'COMPONENT', 'HOOK', 'STORE', 'TEST', 'SCRIPT', 'SNIPPET', 'DOCUMENT', 'CUSTOM')),
    CONSTRAINT blueprint_nodes_origin_check CHECK (origin IN ('DETECTED', 'MANUAL')),
    CONSTRAINT blueprint_nodes_status_check CHECK (status IN ('PLANNED', 'IN_PROGRESS', 'IMPLEMENTED', 'DEPRECATED')),
    CONSTRAINT blueprint_nodes_path_state_check CHECK (path_state IN ('LINKED', 'TO_CREATE', 'DOCUMENT_REFERENCE',
        'VIRTUAL', 'MISSING'))
);
CREATE UNIQUE INDEX blueprint_nodes_key_idx ON blueprint_nodes (project_id, node_key);
CREATE INDEX blueprint_nodes_parent_idx ON blueprint_nodes (parent_id);

CREATE TABLE blueprint_edges (
    id              BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id      BIGINT        NOT NULL REFERENCES projects (id),
    source_node_id  BIGINT        NOT NULL REFERENCES blueprint_nodes (id) ON DELETE CASCADE,
    target_node_id  BIGINT        NOT NULL REFERENCES blueprint_nodes (id) ON DELETE CASCADE,
    relation        VARCHAR(32)   NOT NULL,
    origin          VARCHAR(16)   NOT NULL,
    label           VARCHAR(255),
    description     VARCHAR(2000),
    code_path       VARCHAR(1000),
    code_line       INTEGER,
    code_excerpt    VARCHAR(500),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    version         BIGINT        NOT NULL DEFAULT 0,

    CONSTRAINT blueprint_edges_relation_check CHECK (relation IN ('IMPORTS', 'USES', 'CALLS', 'EXTENDS',
        'IMPLEMENTS', 'READS', 'WRITES', 'CREATES', 'CONTAINS', 'BELONGS_TO', 'VALIDATES', 'EMITS', 'SUBSCRIBES',
        'MAPS_TO', 'ENDPOINT_TO_SERVICE', 'SERVICE_TO_REPOSITORY', 'ENTITY_TO_TABLE', 'TEST_COVERS', 'CUSTOM')),
    CONSTRAINT blueprint_edges_origin_check CHECK (origin IN ('DETECTED', 'MANUAL', 'PROPOSED')),
    CONSTRAINT blueprint_edges_not_a_loop CHECK (source_node_id <> target_node_id)
);
CREATE UNIQUE INDEX blueprint_edges_unique_idx ON blueprint_edges (source_node_id, target_node_id, relation);
CREATE INDEX blueprint_edges_project_idx ON blueprint_edges (project_id);
CREATE INDEX blueprint_edges_target_idx ON blueprint_edges (target_node_id);

-- Positions live apart from the nodes (ADR-033 §6): dragging a block must not
-- bump the version the Inspector holds for the same node.
CREATE TABLE blueprint_layouts (
    project_id      BIGINT        PRIMARY KEY REFERENCES projects (id),
    positions       TEXT          NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    version         BIGINT        NOT NULL DEFAULT 0
);

CREATE TABLE blueprint_scans (
    id              BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id      BIGINT        NOT NULL REFERENCES projects (id),
    started_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    requested_by    VARCHAR(255)  NOT NULL,
    files           INTEGER       NOT NULL,
    truncated       BOOLEAN       NOT NULL,
    nodes_detected  INTEGER       NOT NULL,
    edges_detected  INTEGER       NOT NULL,
    nodes_added     INTEGER       NOT NULL,
    nodes_missing   INTEGER       NOT NULL,
    unresolved      INTEGER       NOT NULL,
    languages       VARCHAR(500)  NOT NULL
);
CREATE INDEX blueprint_scans_project_idx ON blueprint_scans (project_id, id);

CREATE TABLE blueprint_change_proposals (
    id              BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id      BIGINT        NOT NULL REFERENCES projects (id),
    node_id         BIGINT        REFERENCES blueprint_nodes (id) ON DELETE SET NULL,
    edge_id         BIGINT        REFERENCES blueprint_edges (id) ON DELETE SET NULL,
    kind            VARCHAR(24)   NOT NULL,
    status          VARCHAR(16)   NOT NULL,
    file_path       VARCHAR(1000) NOT NULL,
    title           VARCHAR(255)  NOT NULL,
    reason          VARCHAR(2000),
    consequences    VARCHAR(2000),
    diff            TEXT          NOT NULL,
    task_id         BIGINT        REFERENCES tasks (id),
    proposed_by     VARCHAR(255)  NOT NULL,
    decided_by      VARCHAR(255),
    decided_at      TIMESTAMP WITH TIME ZONE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    version         BIGINT        NOT NULL DEFAULT 0,

    CONSTRAINT blueprint_proposals_kind_check CHECK (kind IN ('CREATE_FILE', 'ADD_DEPENDENCY', 'CUSTOM')),
    CONSTRAINT blueprint_proposals_status_check CHECK (status IN ('PROPOSED', 'ACCEPTED', 'REJECTED'))
);
CREATE INDEX blueprint_proposals_project_idx ON blueprint_change_proposals (project_id, id);
CREATE INDEX blueprint_proposals_task_idx ON blueprint_change_proposals (task_id);
